export function spriteSize(name) {
	const rows = SPRITES[name];
	return { w: rows[0].length, h: rows.length };
}

export function drawSprite(ctx, name, x, y, options = {}) {
	const rows = SPRITES[name];
	if (!rows) return;
	const flip = Boolean(options.flip);
	const flipY = Boolean(options.flipY);
	const replace = options.replace ?? null;
	const height = rows.length;
	const width = rows[0].length;
	const originX = Math.round(x);
	const originY = Math.round(y);
	for (let row = 0; row < height; row += 1) {
		const line = rows[row];
		const py = flipY ? height - 1 - row : row;
		for (let col = 0; col < width; col += 1) {
			const key = line[col];
			if (!key || key === '.' || key === ' ') continue;
			const color = (replace && replace[key]) || PALETTE[key];
			if (!color) continue;
			const px = flip ? width - 1 - col : col;
			ctx.fillStyle = color;
			ctx.fillRect(originX + px, originY + py, 1, 1);
		}
	}
}

export function drawActor(ctx, name, box, options) {
	const size = spriteSize(name);
	const x = box.x + (box.w - size.w) / 2;
	const y = box.y + box.h - size.h;
	drawSprite(ctx, name, x, y, options);
}
